/* Makes the "paste into Koha" copies from the documented masters.
   Strips comments only — nothing is renamed, reordered or rewritten.
   Run with:  node build.js
*/
const fs = require('fs');
const terser = require('terser');
process.chdir(__dirname);   // masters and paste copies sit beside this script

/* CSS comment stripper that understands strings and url(), so a /* inside
   a quoted value or a font URL can never be mistaken for a comment. */
function stripCss(src) {
  let out = '', i = 0, quote = null;
  while (i < src.length) {
    const c = src[i], d = src[i + 1];
    if (quote) {
      out += c;
      if (c === '\\') { out += src[i + 1] || ''; i += 2; continue; }
      if (c === quote) quote = null;
      i++; continue;
    }
    if (c === '"' || c === "'") { quote = c; out += c; i++; continue; }
    if (c === '/' && d === '*') {
      const end = src.indexOf('*/', i + 2);
      i = end === -1 ? src.length : end + 2;
      continue;
    }
    out += c; i++;
  }
  return out
    .split('\n')
    .map(l => l.replace(/\s+$/, ''))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim() + '\n';
}

function banner(from, kind) {
  const c = kind === 'css' ? ['/*', '*/'] : ['/*', '*/'];
  return `${c[0]} Maktabat Aljamea (Sindh) — generated from ${from}
   This is the copy to paste into Koha: identical rules, comments removed.
   DO NOT EDIT THIS FILE. Edit ${from} and run build.js again. ${c[1]}\n`;
}

(async () => {
  const jobs = [
    ['OPACUserCSS_V7.css', 'OPACUserCSS_V7.paste.css', 'css'],
    ['SCOUserCSS_V1.css', 'SCOUserCSS_V1.paste.css', 'css'],
    ['OPACUserJS_V7.js', 'OPACUserJS_V7.paste.js', 'js'],
    ['SCOUserJS_V1.js', 'SCOUserJS_V1.paste.js', 'js'],
  ];

  for (const [from, to, kind] of jobs) {
    const src = fs.readFileSync(from, 'utf8');
    let body;
    if (kind === 'css') {
      // SCOUserCSS starts with @import, which must stay the very first thing
      // in the stylesheet. Match to the closing ");" — the font URL itself
      // contains semicolons (wght@400;700), so stopping at the first one
      // cuts the rule in half.
      body = stripCss(src);
      const m = body.match(/^\s*(@import\s+url\((["']).*?\2\)\s*;)\s*/);
      if (m) body = m[1] + '\n' + banner(from.split('/').pop(), kind) + body.slice(m[0].length);
      else body = banner(from.split('/').pop(), kind) + body;
    } else {
      const r = await terser.minify(src, {
        compress: false, mangle: false,
        format: { comments: false, beautify: true, indent_level: 2 },
      });
      if (r.error) throw r.error;
      body = banner(from.split('/').pop(), kind) + r.code + '\n';
    }
    // Never ship a generated file that does not parse.
    if (kind === 'css') {
      const errs = [];
      require('css-tree').parse(body, { positions: true,
        onParseError: e => errs.push(`line ${e.line}: ${e.message}`) });
      if (errs.length) { throw new Error(`${to} failed to parse:\n  ` + errs.join('\n  ')); }
    } else {
      new (require('vm').Script)(body, { filename: to });   // throws on a syntax error
    }
    fs.writeFileSync(to, body);
    const gz = s => require('zlib').gzipSync(s).length;
    console.log(`${to.padEnd(34)} ${String(src.length).padStart(6)} -> ${String(body.length).padStart(6)} bytes   ` +
                `(gzipped ${gz(src)} -> ${gz(body)})`);
  }
})();
